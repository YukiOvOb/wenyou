def check():
    """自查：人物基本信息齐全、基础栏没有空值；开局选项字段齐全，stats 键都在 STATS 里；overrides 的键都是存在的人物，stats 键在 CHAR_STATS 里；主线节点字段齐全；style 为空。"""
    stat_keys = {s["key"] for s in STATS}
    char_keys = {s["key"] for s in CHAR_STATS}
    names = {c["name"] for c in CHARS}
    all_chars = list(CHARS) + [c for f in CREATION["fields"] for o in f["options"] for c in o.get("characters", [])]
    problems = []
    for c in all_chars:
        for k in ("gender", "age", "stats", "now", "address", "importance"):
            if not c.get(k) and c.get(k) != 0:
                problems.append(f"{c['name']} 缺 {k}")
        if set(c.get("stats", {})) != char_keys:
            problems.append(f"{c['name']} 的 stats 键不对：{sorted(c.get('stats', {}))}")
        for k, v in c.get("stats", {}).items():
            if not str(v).strip():
                problems.append(f"{c['name']} 的 {k} 是空的")
    assert len({c["name"] for c in all_chars}) == len(all_chars), "人物重名"
    for f in CREATION["fields"]:
        for o in f["options"]:
            for k in ("id", "label", "weight", "desc"):
                if not o.get(k):
                    problems.append(f"{f['key']} 的选项 {o.get('id')} 缺 {k}")
            for k in o.get("stats", {}):
                if k not in stat_keys:
                    problems.append(f"{o['id']} 的 stats 键 {k} 不在 STATS 里")
            for ba in o.get("byAge", {}).values():
                for k in ba:
                    if k not in stat_keys:
                        problems.append(f"{o['id']} 的 byAge 键 {k} 不在 STATS 里")
            for n, ov in o.get("overrides", {}).items():
                if n not in names:
                    problems.append(f"{o['id']} 的 overrides 人物 {n} 不存在")
                for k in ov.get("stats", {}):
                    if k not in char_keys:
                        problems.append(f"{o['id']} 的 overrides 人物 {n} 的 stats 键 {k} 不在 CHAR_STATS 里")
    assert SCRIPT["style"] == "", "style 要为空"
    assert len({m["id"] for m in MILESTONES}) == len(MILESTONES), "主线节点 id 重复"
    assert MILESTONES[0].get("initial") == "active", "第一个主线节点要是 active"
    assert all(m.get(k) for m in MILESTONES for k in ("id", "title", "canon", "hook")), "主线节点缺字段"
    assert not problems, "\n".join(problems)


